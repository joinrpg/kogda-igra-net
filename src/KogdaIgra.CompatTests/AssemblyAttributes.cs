// Все тесты в сборке выполняются последовательно.
//
// Сайт и его БД в compat-тестах одни на весь прогон (фикстура PerTestSession), а
// write-тесты пересоздают схему через ResetDatabaseAsync. Если параллельно с этим
// read-тест сделает запрос, он увидит наполовину снесённую базу и упадёт с
// необъяснимой ошибкой. Пометки [NotInParallel] на одном классе тут мало: она
// разводит только те тесты, что её несут, а read-тесты продолжали бы идти рядом.
//
// Цена — прогон в одном потоке; при нынешнем размере набора это единицы секунд.
[assembly: NotInParallel]
